/**
 * 企业名称核名预检（2026-09-19 新建）
 *
 * ══ 决策人的担心是对的，但可以拆成两半 ══
 *
 * 决策人 2026-09-19：「公司起名最好也加进来，不过这个公司起名更怕工商局核验通不过。」
 *
 * 核名能否通过取决于两件事，我们的能力边界在中间划开：
 *
 * | | 我们能做 | 我们做不了 |
 * |---|---|---|
 * | **禁限用规则** | ✅ 《企业名称登记管理规定》《企业名称禁限用规则》条文明确，可编码 | |
 * | **同行业查重** | | ❌ 需国家企业信用信息公示系统数据，无接口即无从查 |
 *
 * 故本模块的定位是 **「核名预检」不是「保证通过」**——
 * 把必然驳回的先滤掉、把通过率提上去，同时明确告诉用户
 * 最终以工商核定为准。**不能让用户以为我们能担保。**
 * 这一条写进 `disclaimer` 字段，每次调用都带出去。
 *
 * ══ 规则出处 ══
 *
 * · 《企业名称登记管理规定》（国务院令第 734 号，2021-03-01 施行）
 * · 《企业名称禁限用规则》（原工商总局印发）
 *
 * 与本轮的教训一致：**取有名有姓的源头，不拼来路不明的表**。
 */

import { isGuifanHanzi } from "./naming-pool";

/** 企业名称的四段结构：行政区划 ＋ 字号 ＋ 行业 ＋ 组织形式 */
export interface CompanyNameParts {
  /** 行政区划，如「杭州市」「浙江省」 */
  region?: string;
  /** 字号（商号），如「阿里巴巴」 */
  ziHao: string;
  /** 行业或经营特点，如「网络科技」 */
  industry?: string;
  /** 组织形式，如「有限公司」「股份有限公司」 */
  form?: string;
}

export type CheckLevel = "驳回" | "需核准" | "提示";

export interface CheckIssue {
  level: CheckLevel;
  /** 命中的规则名 */
  rule: string;
  message: string;
  /** 条文依据 */
  basis: string;
}

export interface CompanyNameCheckResult {
  parts: CompanyNameParts;
  issues: CheckIssue[];
  /**
   * 可自主申报——无「驳回」也无「需核准」级问题。
   *
   * 「需核准」单独排除是有意的：冠「中国」等字样须国务院决定设立，
   * 普通企业**根本无法自主申报**。若只看有无驳回就标「通过」，
   * 用户会以为这名字能用——那比直接说不行更误导。
   */
  canSelfApply: boolean;
  /** 仅无「驳回」级问题。为 true 但 `canSelfApply` 为 false 者，即须报批之名 */
  noRejection: boolean;
  disclaimer: string;
}

const DISCLAIMER =
  "本结果为规则预检，仅排除依《企业名称登记管理规定》必然驳回的情形；" +
  "**不含同行业重名与近似比对**（需国家企业信用信息公示系统数据），" +
  "最终以登记机关核定为准。";

// ─────────────────── 规则表 ───────────────────

/** 须国务院批准方可冠用的字样 */
const NEED_APPROVAL = ["中国", "中华", "全国", "国家", "国际"];

/** 组织形式（不得用作字号） */
const FORMS = [
  "有限公司", "股份有限公司", "有限责任公司", "合伙企业", "个人独资企业",
  "集团有限公司", "股份公司", "总公司", "分公司", "公司", "厂", "店", "中心", "工作室",
];

/** 常见行业用语（不得用作字号） */
const INDUSTRY_WORDS = [
  "科技", "技术", "贸易", "商贸", "实业", "投资", "咨询", "服务", "管理", "文化",
  "传媒", "教育", "医疗", "健康", "食品", "建筑", "装饰", "物流", "运输", "制造",
  "electronics", "网络", "信息", "数据", "金融", "地产", "置业", "农业", "能源",
];

/** 政治、军事、宗教等禁用词 */
const FORBIDDEN: { re: RegExp; rule: string; msg: string }[] = [
  { re: /共产党|国民党|民主党|政协|人大常委|中央委员/, rule: "政党机关", msg: "不得含政党、党政机关名称" },
  { re: /解放军|武警|国防|军区|军委/, rule: "军事", msg: "不得含军队名称" },
  { re: /工会|共青团|妇联|红十字/, rule: "群众团体", msg: "不得含群众团体名称" },
  { re: /联合国|世贸组织|世界卫生|欧盟|北约/, rule: "国际组织", msg: "不得含国际组织名称" },
  { re: /佛祖|菩萨|耶稣|真主|安拉|上帝/, rule: "宗教", msg: "不得含可能造成宗教误解的内容" },
  { re: /第一|最好|最优|最佳|顶级|顶尖|独家|唯一|无敌|超级|极品/, rule: "绝对化用语", msg: "不得使用可能欺骗或使人误解的绝对化用语" },
  { re: /色情|赌博|毒品|走私|诈骗/, rule: "违法内容", msg: "不得含损害社会公共利益的内容" },
];

/** 外国国家名（择常见者；完整名单以登记机关为准） */
const FOREIGN_COUNTRIES = [
  "美国", "英国", "法国", "德国", "日本", "韩国", "俄罗斯", "意大利", "加拿大",
  "澳大利亚", "新加坡", "印度", "巴西", "西班牙", "瑞士", "瑞典", "荷兰",
];

// ─────────────────── 检查 ───────────────────

/**
 * 逐条核名预检。
 *
 * 分三级：
 * · **驳回**——依规定必然不予核准；
 * · **需核准**——须报国务院或上级机关批准，非普通企业可自主申报；
 * · **提示**——不违规但通过率低或易生歧义。
 */
export function checkCompanyName(parts: CompanyNameParts): CompanyNameCheckResult {
  const { region = "", ziHao, industry = "", form = "" } = parts;
  const full = `${region}${ziHao}${industry}${form}`;
  const issues: CheckIssue[] = [];
  const add = (level: CheckLevel, rule: string, message: string, basis: string) =>
    issues.push({ level, rule, message, basis });

  // ① 字号须由 2 个以上规范汉字组成
  const zi = [...ziHao];
  if (zi.length < 2) {
    add("驳回", "字号长度", "字号应由 2 个以上汉字组成，单字字号不予核准",
      "《企业名称登记管理规定》：字号应当由 2 个以上的符合国家规范的汉字组成");
  }
  const notGuifan = zi.filter((c) => !isGuifanHanzi(c));
  if (notGuifan.length) {
    add("驳回", "非规范汉字", `字号含非规范汉字「${notGuifan.join("")}」`,
      "同上：须为符合国家规范的汉字。本项依《通用规范汉字表》（8105 字）核验");
  }
  if (/[a-zA-Z0-9]/.test(ziHao)) {
    add("驳回", "字母数字", "字号不得含汉语拼音字母或阿拉伯数字",
      "《企业名称登记管理规定》：不得含有汉语拼音字母、阿拉伯数字");
  }

  // ② 行政区划、行业、组织形式不得用作字号
  for (const w of FORMS) {
    if (ziHao.includes(w)) {
      add("驳回", "字号含组织形式", `字号不得含组织形式「${w}」`,
        "《企业名称登记管理规定》：行政区划、行业、组织形式不得用作字号");
      break;
    }
  }
  for (const w of INDUSTRY_WORDS) {
    if (ziHao.includes(w)) {
      add("驳回", "字号含行业用语", `字号不得含行业用语「${w}」`,
        "同上");
      break;
    }
  }
  if (/省|市|县|区$|自治区|特别行政区/.test(ziHao)) {
    add("驳回", "字号含行政区划", "字号不得含行政区划",
      "同上");
  }

  // ③ 冠用「中国」等字样
  for (const w of NEED_APPROVAL) {
    if (!full.includes(w)) continue;
    // 冠于名称之首者须国务院决定设立；置于中间且作行业限定语的另论
    if (full.startsWith(w) || ziHao.startsWith(w)) {
      add("需核准", "冠用国字号", `冠以「${w}」须为国务院决定设立的企业`,
        "《企业名称登记管理规定》：除国务院决定设立的企业外，企业名称不得冠以「中国」「中华」「全国」「国家」「国际」等字样");
    } else {
      add("提示", "中间使用国字号", `名称中间使用「${w}」时，该字样须为行业限定语，且一般需总局核准（「国际」除外）`,
        "同上：在企业名称中间使用的，该字样应是行业的限定语");
    }
  }

  // ④ 禁用内容
  for (const f of FORBIDDEN) {
    if (f.re.test(full)) {
      add("驳回", f.rule, f.msg,
        "《企业名称登记管理规定》第十一条：不得损害国家利益、社会公共利益，不得可能欺骗或者使人误解");
    }
  }
  for (const c of FOREIGN_COUNTRIES) {
    if (full.includes(c)) {
      add("驳回", "外国国名", `不得含外国（地区）国名「${c}」`,
        "《企业名称登记管理规定》：不得含有外国国家（地区）名称、国际组织名称");
      break;
    }
  }

  // ⑤ 结构完整性（提示级——自主申报时由系统补全，但缺项会增加驳回风险）
  if (!industry) add("提示", "缺行业表述", "名称通常应含行业或经营特点，缺失会增加驳回风险",
    "《企业名称登记管理规定》：企业名称由行政区划、字号、行业、组织形式依次组成");
  if (!form) add("提示", "缺组织形式", "名称应含组织形式（如「有限公司」）", "同上");

  // ⑥ 通过率提示（非规则，仅经验）
  if (zi.length === 2) add("提示", "两字字号", "两字字号重名率高，核名通过率明显低于三四字",
    "经验提示，非法规要求");

  return {
    parts,
    issues,
    noRejection: !issues.some((i) => i.level === "驳回"),
    canSelfApply: !issues.some((i) => i.level === "驳回" || i.level === "需核准"),
    disclaimer: DISCLAIMER,
  };
}

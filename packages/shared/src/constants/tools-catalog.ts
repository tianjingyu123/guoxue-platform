export function getToolsDirectory() {
  const groups: ToolCategoryGroup[] = [];
  const catMap = new Map<string, ToolEntry[]>();
  for (const tool of ALL_TOOLS) {
    const list = catMap.get(tool.category) || [];
    list.push(tool);
    catMap.set(tool.category, list);
  }
  for (const [category, tools] of catMap) {
    const catInfo = CATEGORY_LABELS[category] || { label: category, icon: "help" };
    groups.push({ category: category as ToolCategoryGroup["category"], label: catInfo.label, icon: catInfo.icon, tools: tools.sort((a, b) => a.sortOrder - b.sortOrder) });
  }
  return { groups, total: ALL_TOOLS.length };
}

export function getToolById(id: string): ToolEntry | undefined {
  return ALL_TOOLS.find((t) => t.id === id);
}

export function getToolsByCategory(category: string): ToolEntry[] {
  return ALL_TOOLS.filter((t) => t.category === category).sort((a, b) => a.sortOrder - b.sortOrder);
}

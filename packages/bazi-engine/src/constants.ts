/** 空亡表（日柱旬空） */
export function getKongWang(riGanZhi: string): string {
  const riIndex = GAN.indexOf(riGanZhi[0] as Gan)
  const zhiIndex = ZHI.indexOf(riGanZhi[1] as Zhi)
  const xunIndex = zhiIndex - (riIndex % 10)
  const kong1 = (xunIndex + 10) % 12
  const kong2 = (kong1 + 1) % 12
  return ZHI[kong1] + ZHI[kong2]
}

/** 六枚铜钱（自下而上爻位一至六）：true=字面(阳) false=背面(阴) */
export type CoinCast = [boolean, boolean, boolean, boolean, boolean, boolean]

/** 由六爻求卦名：lines 自下而上 */
export function castToHexName(cast: CoinCast): string {
  const lower = cast.slice(0, 3) as boolean[]
  const upper = cast.slice(3, 6) as boolean[]
  const findGua = (ls: boolean[]) => {
    for (const [name, def] of Object.entries(BAGUA_LINES)) {
      if (def[0] === ls[0] && def[1] === ls[1] && def[2] === ls[2]) return name
    }
    return "乾"
  }
  const BAGUA_NUM: Record<string, number> = { 乾: 1, 兑: 2, 离: 3, 震: 4, 巽: 5, 坎: 6, 艮: 7, 坤: 8 }
  return HEX_NAMES[BAGUA_NUM[findGua(upper)]][BAGUA_NUM[findGua(lower)]]
}


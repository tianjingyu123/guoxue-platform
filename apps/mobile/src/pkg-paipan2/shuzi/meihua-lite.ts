export function getTiyongRelation(tiWx: string, yongWx: string): TiyongRelation {
  if (tiWx === yongWx) return "比和"
  if (WX_SHENG[yongWx] === tiWx) return "用生体"
  if (WX_KE[tiWx] === yongWx) return "体克用"
  if (WX_SHENG[tiWx] === yongWx) return "体生用"
  return "用克体"
}


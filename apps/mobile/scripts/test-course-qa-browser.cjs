const assert = require('node:assert/strict')
const path = require('node:path')
const puppeteer = require('puppeteer')

async function run() {
  await fetch('http://127.0.0.1:3989/__question_mode?mode=ERROR')
  const browser = await puppeteer.launch({ headless: true, executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
  try {
    const page = await browser.newPage()
    await page.setViewport({ width: 320, height: 760 })
    await page.setRequestInterception(true)
    page.on('request', (request) => {
      if (request.url().startsWith('http://127.0.0.1:') || /^(data:|blob:|about:)/.test(request.url())) request.continue()
      else request.abort()
    })
    await page.goto('http://127.0.0.1:5178/h5/', { waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => Boolean(window.uni))
    await page.evaluate(() => {
      window.uni.setStorageSync('auth_token', 'synthetic-token')
      window.uni.navigateTo({ url: '/pkg-course/qa/index?id=free-1' })
    })
    await page.waitForFunction(() => document.body.innerText.includes('问答加载失败'), { timeout: 30000 })
    assert(!await page.evaluate(() => document.body.innerText.includes('还没有提问')))
    await fetch('http://127.0.0.1:3989/__question_mode?mode=READY')
    await page.evaluate(() => [...document.querySelectorAll('*')].find((e) => e.textContent?.trim() === '重试')?.click())
    await page.waitForFunction(() => document.body.innerText.includes('第一笔应该如何起笔？'), { timeout: 30000 })
    const loaded = await page.evaluate(() => ({ text: document.body.innerText, width: document.documentElement.scrollWidth, viewport: innerWidth }))
    assert(loaded.text.includes('先保持笔锋稳定，再逐步加压。'))
    assert(loaded.text.includes('查看更多问题'))
    assert(loaded.width <= loaded.viewport + 2)
    const screenshot = path.join(process.env.TEMP || '/tmp', 'rebu-course-qa-320.png')
    await page.screenshot({ path: screenshot })
    await page.evaluate(() => [...document.querySelectorAll('*')].find((e) => e.textContent?.trim() === '查看更多问题')?.click())
    await page.waitForFunction(() => document.body.innerText.includes('已关闭的问题'), { timeout: 30000 })
    const afterMore = await page.evaluate(() => document.body.innerText)
    assert(afterMore.includes('问题已关闭'))
    assert(!afterMore.includes('讲师回答后会通知你'))
    await fetch('http://127.0.0.1:3989/__question_mode?mode=EMPTY')
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => document.body.innerText.includes('还没有提问'), { timeout: 30000 })
    assert(!await page.evaluate(() => document.body.innerText.includes('问答加载失败')))
    process.stdout.write(`course QA synthetic HTTP: error separated from empty, question/answer fields, pagination and closed status; 320px fits; screenshot=${screenshot}\n`)
  } finally {
    await browser.close()
  }
}
run().catch((error) => { console.error(error); process.exitCode = 1 })

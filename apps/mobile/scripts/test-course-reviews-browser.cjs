const assert = require('node:assert/strict')
const path = require('node:path')
const puppeteer = require('puppeteer')

async function run() {
  await fetch('http://127.0.0.1:3989/__review_mode?mode=READY')
  await fetch('http://127.0.0.1:3989/__user_has_reviewed?enabled=0')
  const browser = await puppeteer.launch({ headless: true, executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
  try {
    const page = await browser.newPage()
    await page.setViewport({ width: 320, height: 760 })
    await page.setRequestInterception(true)
    page.on('request', (request) => {
      if (request.url().startsWith('http://127.0.0.1:') || /^(data:|blob:|about:)/.test(request.url())) request.continue()
      else request.abort()
    })
    await page.goto('http://127.0.0.1:5178/h5/', { waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => Boolean(window.uni))
    await page.evaluate(() => {
      window.uni.setStorageSync('auth_token', 'synthetic-token')
      window.uni.navigateTo({ url: '/pkg-course/reviews/index?id=reviews-1' })
    })
    await page.waitForFunction(() => document.body.innerText.includes('第一条真实评价'), { timeout: 30000 })
    const first = await page.evaluate(() => ({ text: document.body.innerText, width: document.documentElement.scrollWidth, viewport: innerWidth }))
    assert(first.text.includes('4.2'))
    assert(first.text.includes('共 21 条公开评价'))
    assert(first.text.includes('查看更多评价'))
    assert(first.text.includes('写个评价'))
    assert(!first.text.includes('100%'))
    assert(first.width <= first.viewport + 2)
    const screenshot = path.join(process.env.TEMP || '/tmp', 'rebu-course-reviews-320.png')
    await page.screenshot({ path: screenshot })
    await page.evaluate(() => [...document.querySelectorAll('*')].find((e) => e.textContent?.trim() === '查看更多评价')?.click())
    await page.waitForFunction(() => document.body.innerText.includes('第二页评价'), { timeout: 30000 })
    await fetch('http://127.0.0.1:3989/__user_has_reviewed?enabled=1')
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => document.body.innerText.includes('第一条真实评价'), { timeout: 30000 })
    await page.waitForFunction(() => !document.body.innerText.includes('写个评价'), { timeout: 30000 })
    await fetch('http://127.0.0.1:3989/__review_mode?mode=RATING_ERROR')
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => document.body.innerText.includes('第一条真实评价'), { timeout: 30000 })
    const ratingFailed = await page.evaluate(() => document.body.innerText)
    assert(ratingFailed.includes('共 21 条公开评价'))
    assert(!ratingFailed.includes('4.2'))
    await fetch('http://127.0.0.1:3989/__review_mode?mode=ERROR')
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => document.body.innerText.includes('重试'), { timeout: 30000 })
    assert(!await page.evaluate(() => document.body.innerText.includes('还没有评价')))
    process.stdout.write(`course reviews synthetic HTTP: server-wide rating/count, page 2, own reviewed state, rating failure fallback, list error; 320px fits; screenshot=${screenshot}\n`)
  } finally {
    await browser.close()
  }
}
run().catch((error) => { console.error(error); process.exitCode = 1 })

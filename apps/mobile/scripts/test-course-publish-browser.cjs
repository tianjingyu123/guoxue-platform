const assert = require('node:assert/strict')
const path = require('node:path')
const puppeteer = require('puppeteer')

async function run() {
  await fetch('http://127.0.0.1:3989/__reset')
  await fetch('http://127.0.0.1:3989/__teacher_cert_mode?mode=ERROR')
  const browser = await puppeteer.launch({ headless: true, executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
  try {
    const page = await browser.newPage()
    await page.setViewport({ width: 320, height: 760 })
    await page.setRequestInterception(true)
    page.on('request', (request) => {
      if (request.url().startsWith('http://127.0.0.1:') || /^(data:|blob:|about:)/.test(request.url())) request.continue()
      else request.abort()
    })
    await page.goto('http://127.0.0.1:5178/h5/', { waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => Boolean(window.uni))
    await page.evaluate(() => {
      window.uni.setStorageSync('auth_token', 'synthetic-token')
      window.uni.navigateTo({ url: '/pkg-course/publish-course/index' })
    })
    await page.waitForFunction(() => document.body.innerText.includes('暂无法核对讲师资格'), { timeout: 30000 })
    assert(!await page.evaluate(() => document.body.innerText.includes('需先成为认证讲师')))
    await fetch('http://127.0.0.1:3989/__teacher_cert_mode?mode=APPROVED')
    await page.evaluate(() => [...document.querySelectorAll('*')].find((e) => e.textContent?.trim() === '重试')?.click())
    await page.waitForFunction(() => document.body.innerText.includes('课程封面'), { timeout: 30000 })
    const form = await page.evaluate(() => ({ text: document.body.innerText, width: document.documentElement.scrollWidth, viewport: innerWidth }))
    assert(form.text.includes('可选，建议尺寸'))
    assert(!form.text.includes('审核通过后自动上架'))
    assert(form.width <= form.viewport + 2)
    const screenshot = path.join(process.env.TEMP || '/tmp', 'rebu-course-publish-320.png')
    await page.screenshot({ path: screenshot })
    await page.type('.pc-field-input input', '合成书法课程')
    await page.type('.pc-price-input input', '-1')
    await page.click('.pc-submit')
    await new Promise((resolve) => setTimeout(resolve, 300))
    const invalidCount = await (await fetch('http://127.0.0.1:3989/__course_create_count')).json()
    assert.equal(invalidCount.data.courseCreateCount, 0)
    await page.click('.pc-price-input input')
    await page.keyboard.down('Control')
    await page.keyboard.press('A')
    await page.keyboard.up('Control')
    await page.keyboard.press('Backspace')
    await page.type('.pc-price-input input', '12.50')
    await page.click('.pc-submit')
    await page.waitForFunction(async () => (await (await fetch('http://127.0.0.1:3989/__course_create_count')).json()).data.courseCreateCount === 1, { timeout: 30000 })
    process.stdout.write(`course publish synthetic HTTP: certification error distinct from none; approved form, optional cover, price guard and synthetic create; 320px fits; screenshot=${screenshot}\n`)
  } finally {
    await browser.close()
  }
}
run().catch((error) => { console.error(error); process.exitCode = 1 })

async function main() {
  await prisma.classicCommentary.deleteMany({ where: { author: AUTHOR } });
  let n = 0;
  for (const d of DOCS) {
    const book = await prisma.classicBook.findFirst({
      where: { title: d.book, status: "PUBLISHED" },
      orderBy: [{ chapterCount: "desc" }, { viewCount: "desc" }],
      select: { id: true },
    });
    if (!book) { console.log(`  ⊘ 未找到《${d.book}》`); continue; }
    await prisma.classicCommentary.create({
      data: {
        bookId: book.id, title: `《${d.book}》深度导读`, author: AUTHOR,
        school: d.school, type: "现代解读", content: d.content, status: "PUBLISHED",
      },
    });
    n++;
    console.log(`  ✓ 《${d.book}》导读已注入`);
  }
  console.log(`\n✅ 名著深度导读注入完成：${n} 篇`);
}

main()
  .catch((e) => { console.error("❌ 失败:", e); process.exit(1); })
  .finally(() => prisma.$disconnect());

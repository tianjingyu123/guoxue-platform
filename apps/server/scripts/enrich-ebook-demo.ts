async function main() {
  // 幂等：清演示数据（cascade 删章节）
  await prisma.ebook.deleteMany({ where: { author: { contains: "热卜国学院" } } });

  const catMap = new Map<string, string>();
  for (const [i, name] of CATEGORIES.entries()) {
    const c = await prisma.ebookCategory.upsert({
      where: { name }, create: { name, sortOrder: i }, update: { sortOrder: i },
    });
    catMap.set(name, c.id);
  }
  console.log(`✅ 分类就绪：${CATEGORIES.length} 个`);

  let n = 0;
  for (const b of BOOKS) {
    const book = await prisma.ebook.create({
      data: {
        title: b.title, author: b.author, categoryId: catMap.get(b.cat),
        description: b.desc, price: b.price, originalPrice: b.original,
        fileType: "EPUB", totalChapters: b.chapters.length, language: "zh-CN",
        memberFree: !!b.memberFree, status: "PUBLISHED",
        viewCount: Math.floor(2000 + b.price * 137), purchaseCount: Math.floor(50 + b.price * 7),
        categoryLevel1: b.cat,
      },
    });
    for (const [i, ch] of b.chapters.entries()) {
      await prisma.ebookChapter.create({
        data: {
          ebookId: book.id, title: ch.title, content: ch.content,
          sortOrder: i, pageStart: i * 10 + 1, pageEnd: i * 10 + 10, freeTrial: !!ch.free,
        },
      });
    }
    n++;
    console.log(`  ✓ 《${b.title}》 ¥${b.price}${b.memberFree ? " · 会员免费" : ""} · ${b.chapters.length}章`);
  }
  console.log(`\n✅ 精品电子书注入完成：${n} 本`);
}

main()
  .catch((e) => { console.error("❌ 失败:", e); process.exit(1); })
  .finally(() => prisma.$disconnect());

export async function seedPoetry(prisma: PrismaClient): Promise<void> {
  const existing = await prisma.poetry.count();
  if (existing > 0) {
    console.log(`✅ 诗词雅集: 已存在 ${existing} 首，跳过`);
    return;
  }

  // 1. 分类
  const catMap = new Map<string, string>();
  for (const c of CATEGORIES) {
    const cat = await prisma.poetryCategory.upsert({
      where: { name: c.name },
      update: { icon: c.icon, intro: c.intro, subCategories: c.subCategories, sortOrder: c.sortOrder },
      create: { name: c.name, icon: c.icon, intro: c.intro, subCategories: c.subCategories, sortOrder: c.sortOrder },
    });
    catMap.set(c.name, cat.id);
  }
  console.log(`✅ 诗词分类: ${CATEGORIES.length} 个`);

  // 2. 合集
  const colMap = new Map<string, string>();
  for (const c of COLLECTIONS) {
    const col = await prisma.poetryCollection.create({
      data: {
        title: c.title, author: c.author, dynasty: c.dynasty,
        category: c.category, excerpt: c.excerpt, likes: c.likes, sortOrder: c.sortOrder,
      },
    });
    colMap.set(c.title, col.id);
  }
  console.log(`✅ 诗词合集: ${COLLECTIONS.length} 个`);

  // 3. 诗词
  let n = 0;
  for (const p of POEMS) {
    const lines = p.content.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
    await prisma.poetry.create({
      data: {
        title: p.title,
        author: p.author,
        dynasty: p.dynasty,
        form: p.form,
        content: p.content,
        // 逐句拼音此处留空数组（拼音生成由后续工具补充），保证句序占位
        pinyin: lines.map(() => ""),
        translation: p.translation,
        appreciation: p.appreciation ?? null,
        tags: p.tags,
        categoryId: catMap.get(p.category) ?? null,
        collectionId: p.collection ? colMap.get(p.collection) ?? null : null,
        authorYears: p.authorYears ?? null,
        authorTitle: p.authorTitle ?? null,
        authorIntro: p.authorIntro ?? null,
        likes: p.likes ?? Math.floor(1000 + Math.random() * 3000), // 仅展示用初始热度，非业务计算
        isRecommended: p.isRecommended ?? false,
        isToday: p.isToday ?? false,
      },
    });
    n += 1;
  }
  console.log(`✅ 诗词雅集: ${n} 首经典诗词`);
}

// 允许独立运行
if (require.main === module) {
  const prisma = new PrismaClient();
  seedPoetry(prisma)
    .then(() => console.log("\n🎉 诗词种子数据填充完成！"))
    .catch((e) => {
      console.error("❌ 诗词种子填充失败:", e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}

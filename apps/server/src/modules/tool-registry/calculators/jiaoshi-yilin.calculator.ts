function buildAdvice(judgment: Judgment): { suitable: string[]; avoid: string[] } {
  const jKey = judgment === "大吉" ? "DA_JI" : judgment === "吉" ? "JI" : judgment === "中" ? "ZHONG" : judgment === "凶" ? "XIONG" : "DA_XIONG";
  return ADVICE[jKey];
}


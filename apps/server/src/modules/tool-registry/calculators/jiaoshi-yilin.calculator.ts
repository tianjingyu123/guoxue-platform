// eslint-disable-next-line @typescript-eslint/no-unused-vars
const TRIGRAM_ELE: Record<string, string> = {
  "乾":"金","兑":"金","离":"火","震":"木","巽":"木","坎":"水","艮":"土","坤":"土",
};

// 五行相生：金生水，水生木，木生火，火生土，土生金
const SHENG_CYCLE: Record<string, string> = {
  "金":"水","水":"木","木":"火","火":"土","土":"金",
};

// 五行相克：金克木，木克土，土克水，水克火，火克金
const KE_CYCLE: Record<string, string> = {
  "金":"木","木":"土","土":"水","水":"火","火":"金",
};

/**
 * 判断五行关系：返回 "生"（base 生 change）, "被生"（change 生 base）,
 * "克"（base 克 change）, "被克"（change 克 base）, "同"（相同）, "和"（其他）
 */
function getElementRelation(baseEle: string, changeEle: string): string {
  if (baseEle === changeEle) return "同";
  if (SHENG_CYCLE[baseEle] === changeEle) return "生";
  if (SHENG_CYCLE[changeEle] === baseEle) return "被生";
  if (KE_CYCLE[baseEle] === changeEle) return "克";
  if (KE_CYCLE[changeEle] === baseEle) return "被克";
  return "和";
}

// ══════════════════════════════════════════════
// 七、确定性哈希（确保相同输入始终相同输出）
// ══════════════════════════════════════════════

function pairHash(base: number, change: number): number {
  return ((base * 31 + change * 17) * 2654435761) >>> 0;
}

function pick<T>(arr: readonly T[], seed: number): T {
  return arr[((seed >>> 0) % arr.length + arr.length) % arr.length];
}

function pickN<T>(arr: readonly T[], n: number, seed: number): T[] {
  const shuffled = [...arr];
  let s = seed >>> 0;
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = (s % (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    s = (s * 1103515245 + 12345) >>> 0;
  }
  return shuffled.slice(0, Math.min(n, shuffled.length));
}

// ══════════════════════════════════════════════
// 八、判断吉凶
// ══════════════════════════════════════════════

type Judgment = "大吉" | "吉" | "中" | "凶" | "大凶";

function determineJudgment(base: number, change: number): Judgment {
  if (base === change) {
    // 自变用预定义
    return GUA[base - 1][6] as Judgment;
  }

  const bEle = GUA[base - 1][5];
  const cEle = GUA[change - 1][5];
  const rel = getElementRelation(bEle, cEle);

  // 基础分 50
  let score = 50;

  // 五行关系对分数的影响
  switch (rel) {
    case "生":   score += 22; break; // 大吉倾向
    case "被生": score += 12; break; // 吉倾向
    case "克":   score -= 12; break; // 凶倾向
    case "被克": score -= 22; break; // 大凶倾向
    case "同":   score += 2;  break; // 微吉
    default:     score += 0;  break; // 和
  }

  // 上卦相同加分
  if (GUA[base - 1][3] === GUA[change - 1][3]) score += 4;
  // 下卦相同加分
  if (GUA[base - 1][4] === GUA[change - 1][4]) score += 4;

  // 确定性微调（-6 到 +6）
  const h = pairHash(base, change);
  score += (h % 13) - 6;

  // 特殊组合微调
  const specialBad = [[11,12],[63,64],[1,12],[2,23],[3,47],[12,11],[64,63]];
  const specialGood = [[40,24],[42,32],[55,35],[11,42],[8,45],[31,41]];
  if (specialBad.some(p => p[0] === base && p[1] === change)) score -= 15;
  if (specialGood.some(p => p[0] === base && p[1] === change)) score += 15;

  // 分数 → 判断（目标分布：大凶10% 凶20% 中35% 吉25% 大吉10%）
  if (score >= 72) return "大吉";
  if (score >= 52) return "吉";
  if (score >= 32) return "中";
  if (score >= 14) return "凶";
  return "大凶";
}

// ══════════════════════════════════════════════
// 九、林辞构造
// ══════════════════════════════════════════════

function buildVerse(base: number, change: number, judgment: Judgment): string {
  const h = pairHash(base, change);
  const b = GUA[base - 1];
  const c = GUA[change - 1];

  // 自变直接返回预写辞
  if (base === change) {
    return SELF_VERSES[base];
  }

  const jPoolKey = judgment === "大吉" ? "DA_JI" : judgment === "吉" ? "JI" : judgment === "中" ? "ZHONG" : judgment === "凶" ? "XIONG" : "DA_XIONG";
  const jPhrases = pickN(POOLS[jPoolKey], 3, h);

  // 六种构辞模式
  const patterns = [
    // 模式1：4句 = 本象 + 变象 + 吉断 + 果报
    () => `${b[7]}，${b[8]}。${jPhrases[0]}${jPhrases[1]}，${c[7]}${c[8]}。`,

    // 模式2：4句 = 本性质 + 吉象 + 变性质 + 果报
    () => `${b[9]}${b[10]}，${jPhrases[0]}${jPhrases[1]}。${c[9]}${c[10]}，${jPhrases[2]}${c[7]}。`,

    // 模式3：4句 = 本象 + 吉断 + 变象 + 总断
    () => `${b[7]}，${jPhrases[0]}${jPhrases[1]}。${c[7]}，${b[8]}${c[8]}。`,

    // 模式4：6句 = 本象 + 吉断1 + 本性质 + 变象 + 吉断2 + 变性质
    () => `${b[7]}${b[8]}，${jPhrases[0]}${jPhrases[1]}。${c[7]}${c[8]}，${jPhrases[2]}${b[9]}。`,

    // 模式5：4句 = 判断意象 + 本象 + 变象 + 结论
    () => `${jPhrases[0]}${jPhrases[1]}，${b[7]}${c[7]}。${b[10]}${c[10]}，${jPhrases[2]}${b[8]}。`,

    // 模式6：4句 = 本象 + 变应 + 意象 + 总断
    () => `${b[7]}，${jPhrases[0]}${b[9]}。${jPhrases[1]}${jPhrases[2]}，${c[8]}${c[10]}。`,
  ];

  const patternIdx = h % patterns.length;
  return patterns[patternIdx]();
}

// ══════════════════════════════════════════════
// 十、释义构造
// ══════════════════════════════════════════════

function buildInterpretation(base: number, change: number, judgment: Judgment): string {
  const h = pairHash(base, change);
  const bName = GUA[base - 1][1];
  const cName = GUA[change - 1][1];

  const jKey = judgment === "大吉" ? "DA_JI" : judgment === "吉" ? "JI" : judgment === "中" ? "ZHONG" : judgment === "凶" ? "XIONG" : "DA_XIONG";
  const templates = INTERP_TEMPLATES[jKey];
  const tmpl = pick(templates, h + base * 7);

  return tmpl
    .replace(/\{base\}/g, bName)
    .replace(/\{change\}/g, cName);
}


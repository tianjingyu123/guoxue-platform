// 十神计算（含阴阳正偏区分）
function getShiShenFull(riGan: string, tGan: string): string {
  const wxR = GAN_WX[riGan];
  const wxT = GAN_WX[tGan];
  if (!wxR || !wxT) return "";
  const yinYangR = GAN.indexOf(riGan) % 2;
  const yinYangT = GAN.indexOf(tGan) % 2;
  const samePolarity = yinYangR === yinYangT;

  if (wxR === wxT) return samePolarity ? "比肩" : "劫财";
  if ((wxR==="木"&&wxT==="水")||(wxR==="火"&&wxT==="木")||(wxR==="土"&&wxT==="火")||(wxR==="金"&&wxT==="土")||(wxR==="水"&&wxT==="金"))
    return samePolarity ? "偏印" : "正印";
  if ((wxR==="木"&&wxT==="火")||(wxR==="火"&&wxT==="土")||(wxR==="土"&&wxT==="金")||(wxR==="金"&&wxT==="水")||(wxR==="水"&&wxT==="木"))
    return samePolarity ? "食神" : "伤官";
  if ((wxR==="木"&&wxT==="金")||(wxR==="火"&&wxT==="水")||(wxR==="土"&&wxT==="木")||(wxR==="金"&&wxT==="火")||(wxR==="水"&&wxT==="土"))
    return samePolarity ? "七杀" : "正官";
  return samePolarity ? "偏财" : "正财";
}


function buildGuaDetail(d: GuaData): GuaCiDetail {
  const yaoCiList: YaoCiDetail[] = d.yc.map(([pos, ci, xj, jx]) => ({
    position: pos, yaoCi: ci, xiangJie: xj,
    jiXiong: (["吉","平","凶"].includes(jx) ? jx : "平") as "吉" | "平" | "凶",
  }));
  const liuQin: Record<string, string> = {};
  const yaoPos = ["初爻","二爻","三爻","四爻","五爻","上爻"];
  d.lq.forEach((lq, i) => { liuQin[yaoPos[i]] = lq; });
  return {
    index: d.i, name: d.n, shangGua: d.s, xiaGua: d.x,
    gong: d.g, wuXing: d.w, shiYao: d.sy, yingYao: d.yy,
    guaCi: d.gc, tuanZhuan: d.tz, xiangZhuan: d.xz,
    yaoCiList, liuQin, liuShou: d.ls, yongShen: d.ys,
    yingQi: d.yq, zongDuan: d.zd,
  };
}


function detectQuestionCategory(question: string): string | null {
  const q = question.toLowerCase();
  if (q.includes("事业") || q.includes("工作") || q.includes("职") || q.includes("考") || q.includes("试")) return "事业";
  if (q.includes("财") || q.includes("钱") || q.includes("投资") || q.includes("生意") || q.includes("赚")) return "财运";
  if (q.includes("感情") || q.includes("婚") || q.includes("恋") || q.includes("爱") || q.includes("姻")) return "感情";
  if (q.includes("健康") || q.includes("病") || q.includes("身体") || q.includes("疾") || q.includes("医")) return "健康";
  if (q.includes("出行") || q.includes("旅行") || q.includes("远") || q.includes("移") || q.includes("迁")) return "出行";
  if (q.includes("官司") || q.includes("诉讼") || q.includes("是非") || q.includes("纠纷") || q.includes("仲裁")) return "官司";
  return null;
}


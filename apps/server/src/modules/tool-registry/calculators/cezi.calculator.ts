function getStrokeCount(char: string): number {
  if (char.length === 0) return 0;
  // 优先查表
  if (STROKE_DB[char] !== undefined) return STROKE_DB[char];
  // 对多字节字符（含偏旁），通过部首推断
  const code = char.charCodeAt(0);
  if (code >= 0x4E00 && code <= 0x9FFF) {
    // 不再使用任何取模估算，未收录的字符保守估计为中等笔画数
    return 10;
  }
  // 非汉字返回1
  return 1;
}

function getStructure(char: string): CeZiResult["deconstruction"]["structure"] {
  if (STRUCTURE_DB[char]) return STRUCTURE_DB[char];

  // 对于未收录的汉字，基于部首偏旁推理
  const code = char.charCodeAt(0);
  if (code < 0x4E00 || code > 0x9FFF) return "独体";

  // 保守默认：大多数未收录的复杂汉字为左右或上下结构
  // 这里返回独体，在实际使用中会被具体的部首检测覆盖
  return "独体";
}


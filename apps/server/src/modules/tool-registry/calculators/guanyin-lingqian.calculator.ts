export function calculateGuanYinLingQian(input: Record<string, unknown>): GuanYinLingQianResult {
  const qianNumber = input.qianNumber as number | undefined;
  const question = (input.question as string) || "";

  let selectedQian: LingQianDetail;

  if (qianNumber !== undefined && qianNumber >= 1 && qianNumber <= 100) {
    const found = QIAN_DB.find((q) => q.number === qianNumber);
    if (found) {
      selectedQian = found;
    } else {
      // fallback: 时间确定性选择
      const idx = (Date.now() % QIAN_DB.length);
      selectedQian = QIAN_DB[idx];
    }
  } else {
    const idx = (Date.now() % QIAN_DB.length);
    selectedQian = QIAN_DB[idx];
  }

  const allQian = QIAN_DB.map((q) => ({
    number: q.number,
    name: q.name,
    level: q.level,
  }));

  // 构建 box-drawing 摘要
  const levelIcon: Record<string, string> = {
    "上上": "★★★", "上吉": "★★★", "中吉": "★★", "中平": "★", "下下": "△",
  };
  const lines: string[] = [
    `┌─ 观音灵签 ─────────────────`,
    `│ 第${selectedQian.number}签 「${selectedQian.name}」 ${levelIcon[selectedQian.level] || ""} ${selectedQian.level}`,
    ...(question ? [`│ 所求：「${question.slice(0, 30)}」`] : []),
    ``,
    `├─ 签诗 ────────────────────`,
    `│ ${selectedQian.poem}`,
    ``,
    `├─ 白话解 ────────────────────`,
    `│ ${selectedQian.baiHua}`,
    ``,
    `├─ 签解 ────────────────────`,
    `│ ${selectedQian.jieYue}`,
    ``,
    `├─ 仙机 ────────────────────`,
    ...Object.entries(selectedQian.xianJi).map(([k, v]) =>
      `│ ${k.padEnd(6, " ")} ${v}`
    ),
    ``,
    `├─ 典故 ────────────────────`,
    `│ ${selectedQian.dianGu.slice(0, 80)}${selectedQian.dianGu.length > 80 ? "…" : ""}`,
    ``,
    `├─ 古籍出处 ──────────────────`,
    `│ 《观音灵签》—— 民间流传最广的灵签，共100签`,
    `│ 观音信仰源自《妙法莲华经·观世音菩萨普门品》`,
    `│ 签诗多以七绝形式，典故出自历史、戏曲、民间故事`,
    `│ 100签中上签36/中签36/下签28，反映人生百态。`,
    ``,
    `└─ 解签提示 ──────────────────`,
    `   「观音签」重于心诚——心诚则灵，疑则不验。`,
    `   签文仅为参考指引，最终命运握在自己手中。`,
    `   上签莫骄，下签莫沮，存好心行好事即是转运之道。`,
  ];
  const summary = lines.join("\n");
  const analysis = question
    ? `所求之事：「${question}」。求得第${selectedQian.number}签「${selectedQian.name}」，${selectedQian.level}之签。${selectedQian.baiHua}`
    : `求得第${selectedQian.number}签「${selectedQian.name}」，${selectedQian.level}之签。${selectedQian.baiHua}`;

  return {
    qian: selectedQian,
    allQian,
    analysis,
    summary,
  } as GuanYinLingQianResult & { summary: string };
}

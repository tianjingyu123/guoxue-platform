// 从模板生成签文
function generateQianWen(qianNum: number): QianWen {
  const guaIdx = (qianNum - 1) % 64;
  const yaoIdx = Math.floor((qianNum - 1) / 64) % 6;
  const gua = GUA_64[guaIdx];
  const yao = YAO_6_TYPES[yaoIdx];

  // 选模板（确定性选择，同一签号总是同一模板）
  const tmplIdx = (qianNum * 17 + guaIdx * 7 + yaoIdx * 13) % QIAN_POEM_TEMPLATES.length;
  const tmpl = QIAN_POEM_TEMPLATES[tmplIdx];

  // 填充模板变量
  const [a, b, c, d] = [0, 1, 2, 3].map(i => gua.keywords[(qianNum + i * 11 + guaIdx * 3) % gua.keywords.length]);
  const seasonMap = ["春","夏","秋","冬"];
  const season = seasonMap[guaIdx % 4];
  const waterWords = ["临","在","向","对"];
  const water = waterWords[qianNum % 4];

  const poem = tmpl
    .replace(/\{a\}/g, a)
    .replace(/\{b\}/g, b)
    .replace(/\{c\}/g, c)
    .replace(/\{d\}/g, d)
    .replace(/\{dir\}/g, gua.direction)
    .replace(/\{elem\}/g, gua.element)
    .replace(/\{season\}/g, season)
    .replace(/\{water\}/g, water)
    .replace(/\{s\}/g, gua.keywords[qianNum % gua.keywords.length]);

  const typeIdx = ["上上","上吉","中上","中平","中下","下下"].indexOf(yao.type);
  let baiHua: string;
  if (typeIdx <= 0) {
    baiHua = `第${qianNum}签，上上大吉。${gua.name}卦${["初","二","三","四","五","上"][yaoIdx]}爻之象。${yao.theme}。${gua.imagery}，${gua.meaning}。凡事积极主动，必有所成。`;
  } else if (typeIdx <= 2) {
    baiHua = `第${qianNum}签，${yao.type}。${gua.name}卦${["初","二","三","四","五","上"][yaoIdx]}爻之象。${yao.theme}。${gua.imagery}，${gua.meaning}。顺势而为则吉。`;
  } else if (typeIdx <= 3) {
    baiHua = `第${qianNum}签，中平。${gua.name}卦${["初","二","三","四","五","上"][yaoIdx]}爻之象。${yao.theme}。${gua.imagery}，${gua.meaning}。宜守不宜攻，顺其自然。`;
  } else {
    baiHua = `第${qianNum}签，${yao.type}。${gua.name}卦${["初","二","三","四","五","上"][yaoIdx]}爻之象。${yao.theme}。虽有阻滞，守正则吉。宜静候时机。`;
  }

  return {
    number: qianNum,
    text: poem,
    type: yao.type,
    gua: gua.name,
    baiHua,
  };
}


// 获取真实笔画数（查表+回退策略）
function getStrokeCount(c: string): number {
  if (CHAR_STROKES[c]) return CHAR_STROKES[c];
  const code = c.charCodeAt(0);
  // CJK基本区 U+4E00-U+9FFF
  if (code >= 0x4E00 && code <= 0x9FFF) {
    // 基于Unicode位置的合理估算：按区块分布估算
    // 常用字在4E00-9FFF间大致按部首笔画分布
    const relativePos = (code - 0x4E00) / (0x9FFF - 0x4E00);
    // 多数常用字在5-20画之间
    return Math.round(5 + relativePos * 15);
  }
  return 2; // 非CJK字符默认少笔画
}


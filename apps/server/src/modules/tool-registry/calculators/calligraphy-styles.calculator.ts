export function calculateCalligraphyStyles(input: Record<string, unknown>): CalligraphyStylesResult {
  const charInput = (input.character as string) || "";
  const script = (input.script as string) || "";
  const master = (input.master as string) || "";

  const character = charInput || "永";
  let styles = FIVE_SCRIPTS;
  if (script) styles = styles.filter(s => s.script.includes(script));
  if (master) styles = styles.filter(s => s.masters.some(m => m.includes(master)));

  const charTip = CHAR_EXAMPLES[character]
    || `「${character}」字在不同书体中呈现各异的风韵。建议先了解该字的篆书字形（《说文解字》），再从楷书入手把握间架结构，逐步贯通各体变化。`;
  const charCount = Object.keys(CHAR_EXAMPLES).length;

  const learningPath = "篆书(练中锋/控笔)→隶书(学笔法/波磔)→楷书(求法度/结构)→行书(通流动/连带)→草书(达气韵/简省)。五体循序渐进，切忌躐等。每练一体至少临300遍基本笔画，再临300字原帖，方得入门。";

  const textSummary = character !== "永"
    ? `五体书法字典：查询字「${character}」→ ${charTip}。本字典包含${charCount}个常用汉字精解，篆隶楷行草五体全面介绍（含历代名家46位/经典碑帖30+），每条含学习建议和入门范本推荐。`
    : `五体书法字典：篆隶楷行草五体全面介绍，含历代名家46位/经典碑帖30+篇/风格特征/入门范本/学习路径。同时提供${charCount}个常用汉字的五体精解。输入任一单字可查询其书法要点。数据来源：《说文解字》《书法大字典》《历代书法论文选》及各名家法帖。`;

  // 构建 box-drawing 摘要
  const lines: string[] = [
    `┌─ 五体书法字典 ─────────────────`,
    `│ 查询字：${character} 收字：${charCount}个`,
  ];

  if (character !== "永" && charTip) {
    lines.push(`│ 精解：${charTip.slice(0, 60)}${charTip.length > 60 ? "…" : ""}`);
  }

  lines.push(`│`);
  lines.push(`├─ 五体纵览 ──────────────────`);
  for (const s of styles) {
    const masterList = s.masters.slice(0, 3).map(m => m.split("(")[0]).join("、");
    lines.push(`│ ▸ ${s.script}`);
    lines.push(`│   ${s.description.slice(0, 55)}${s.description.length > 55 ? "…" : ""}`);
    lines.push(`│   名家：${masterList}…`);
    lines.push(`│   特征：${s.characteristics.slice(0, 50)}${s.characteristics.length > 50 ? "…" : ""}`);
  }

  lines.push(`│`);
  lines.push(`├─ 学习路径 ──────────────────`);
  lines.push(`│ ${learningPath}`);
  lines.push(`│`);
  lines.push(`├─ 古籍出处 ──────────────────`);
  lines.push(`│ 《说文解字》—— 东汉·许慎，540部首/9353字，六书理论奠基`);
  lines.push(`│ 唐·孙过庭《书谱》—— 文书俱佳，书法理论和实践的巅峰之作`);
  lines.push(`│ 宋《淳化阁帖》—— 中国最早的汇集各家书法墨迹的法帖`);
  lines.push(`│ 《历代书法论文选》—— 收录汉至清69家重要书论`);
  lines.push(`│ 清·包世臣《艺舟双楫》—— 碑学理论的开创之作`);
  lines.push(`│`);
  lines.push(`└─ 学书箴言 ──────────────────`);
  lines.push(`   「初学分布，但求平正；既知平正，务追险绝；`);
  lines.push(`    既能险绝，复归平正。」——孙过庭《书谱》`);
  lines.push(`   「学书在法，而其妙在人。法可以人人而传，`);
  lines.push(`    而妙必其胸中之所独得。」——晁补之`);
  const summary = lines.join("\n");

  return { character, styles, learningPath, summary: textSummary, boxSummary: summary } as CalligraphyStylesResult & { boxSummary: string };
}

/** 六爻命名辅助：根据阴阳返回爻名 */
function lineName(pos: number, isYang: boolean): string {
  const prefix = isYang ? "九" : "六";
  if (pos === 1) return `初${prefix}`;
  if (pos === 6) return `上${prefix}`;
  return `${prefix}${["二","三","四","五"][pos - 2]}`;
}


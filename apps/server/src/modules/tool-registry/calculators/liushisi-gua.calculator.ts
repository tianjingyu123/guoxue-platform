export function calculateLiuShiSiGua(input: Record<string, unknown>): LiuShiSiGuaResult {
  const hexagramNumber = Number(input.hexagramNumber);
  if (!Number.isInteger(hexagramNumber) || hexagramNumber < 1 || hexagramNumber > 64) {
    throw new Error(`无效的卦序号：${input.hexagramNumber}，须为 1-64 的整数`);
  }

  const raw = GUA_DB[hexagramNumber];
  const wuXing = TRIGRAM_WUXING[raw.composition.lower] ?? "土";

  const lines: HexagramLine[] = raw.yaoPattern.map((isYang, idx) => ({
    position: idx + 1,
    name: lineName(idx + 1, isYang === 1),
    text: raw.yaoText[idx],
    meaning: raw.yaoMeaning[idx],
  }));

  // ── box-drawing 结构化总结 ──
  const overallIcon = raw.overall === "大吉" ? "★★" : raw.overall === "吉" ? "★" : raw.overall === "中" ? "◆" : raw.overall === "凶" ? "▼" : "▽▽";
  const yaoDisplay = lines.map(l =>
    `│ ${l.name.padEnd(4, " ")} ${l.text.substring(0, 28)}`
  ).join("\n");

  const summary = [
    `┌─ 六十四卦详解 ─────────────────`,
    `│ 第${raw.number}卦 ${raw.symbol} ${raw.name} ${raw.overall} ${overallIcon}`,
    `│ ${raw.composition.upper}上${raw.composition.lower}下 五行：${wuXing}`,
    `│`,
    `├─ 卦辞 ────────────────────`,
    `│ ${raw.judgment}`,
    `│`,
    `├─ 彖传 ────────────────────`,
    `│ ${raw.tuanZhuan.substring(0, 60)}...`,
    `│`,
    `├─ 大象传 ───────────────────`,
    `│ ${raw.xiangZhuan}`,
    `│`,
    `├─ 六爻爻辞 ──────────────────`,
    yaoDisplay,
    `│`,
    `├─ 综合分析 ──────────────────`,
    `│ 事业：${raw.analysis["事业"].substring(0, 50)}...`,
    `│ 财运：${raw.analysis["财运"].substring(0, 50)}...`,
    `│ 感情：${raw.analysis["感情"].substring(0, 50)}...`,
    `│ 健康：${raw.analysis["健康"].substring(0, 50)}...`,
    `│ 关键词：${raw.keywords.join("、")}`,
    `│`,
    `├─ 古籍出处 ──────────────────`,
    `│ 《周易》群经之首，伏羲画卦/文王作辞/孔子作传`,
    `│ 《焦氏易林》汉·焦延寿，六十四卦变四千九十六林辞`,
    `│ 《易林补遗》明·张世宝，筮法要籍`,
    `│`,
    `└─ 观卦提示 ──────────────────`,
    `   ${raw.overall === "大吉" || raw.overall === "吉" ? "吉卦当道，顺势而为，宜积极进取。" : raw.overall === "中" ? "中平之卦，吉凶各半，宜审时度势。" : "凶卦当前，宜守不宜攻，静待时机。"}`,
    `   观卦之法：先观卦辞定吉凶，次观彖传明卦义，再观爻辞辨时位。`,
    `   「居则观其象而玩其辞，动则观其变而玩其占」——系辞上传`,
  ].join("\n");

  return {
    number: raw.number,
    name: raw.name,
    symbol: raw.symbol,
    composition: raw.composition,
    judgment: raw.judgment,
    tuanZhuan: raw.tuanZhuan,
    xiangZhuan: raw.xiangZhuan,
    lines,
    overall: raw.overall,
    wuXing,
    analysis: raw.analysis,
    keywords: raw.keywords,
    summary,
  } as LiuShiSiGuaResult & { summary: string };
}

/** 判断字符是否包含指定字根（部首） */
function charHasRadical(char: string, radical: string): boolean {
  return char === radical || char.includes(radical);
}

/** 分析姓名中单字的生肖适配情况 */
function analyzeCharForShengXiao(
  char: string,
  shengXiao: ShengXiao,
): { xiYong: ShengXiaoNamingEntry["xiYongZiGen"]; jiYong: ShengXiaoNamingEntry["jiYongZiGen"] } {
  const entry = SHENG_XIAO_NAMING[shengXiao];
  const xiYong = entry.xiYongZiGen.filter(r => charHasRadical(char, r.radical));
  const jiYong = entry.jiYongZiGen.filter(r => charHasRadical(char, r.radical));
  return { xiYong, jiYong };
}

/** 获取生肖姓名学完整评分 */
export function getShengXiaoNamingScore(
  name: string,
  shengXiao: ShengXiao,
): {
  shengXiao: ShengXiao;
  score: number;
  xiYongMatches: { char: string; radical: string; desc: string }[];
  jiYongMatches: { char: string; radical: string; desc: string }[];
  heHui: string;
  liuHe: string;
  chong: string;
  hai: string;
  namingTips: string;
  analysis: string;
} {
  const entry = SHENG_XIAO_NAMING[shengXiao];
  const chars = [...name];

  const xiYongMatches: { char: string; radical: string; desc: string }[] = [];
  const jiYongMatches: { char: string; radical: string; desc: string }[] = [];

  for (const char of chars) {
    const { xiYong, jiYong } = analyzeCharForShengXiao(char, shengXiao);
    for (const r of xiYong) {
      xiYongMatches.push({ char, radical: r.radical, desc: r.desc });
    }
    for (const r of jiYong) {
      jiYongMatches.push({ char, radical: r.radical, desc: r.desc });
    }
  }

  // 评分：喜用字根每个+15分，忌用每个-20分，基础60分
  let score = 60 + xiYongMatches.length * 15 - jiYongMatches.length * 20;
  score = Math.max(0, Math.min(100, score));

  const analysis = (() => {
    const parts: string[] = [];
    if (xiYongMatches.length > 0) {
      parts.push(`名字中含${xiYongMatches.length}处喜用字根（${xiYongMatches.map(m => `${m.char}→${m.radical}`).join("、")}），利于${shengXiao}命。`);
    }
    if (jiYongMatches.length > 0) {
      parts.push(`含${jiYongMatches.length}处忌用字根（${jiYongMatches.map(m => `${m.char}→${m.radical}`).join("、")}），对${shengXiao}命不利。`);
    }
    if (xiYongMatches.length === 0 && jiYongMatches.length === 0) {
      parts.push(`名字与${shengXiao}生肖既无相合也无相冲，中平之象。`);
    }
    parts.push(`生肖${shengXiao}：与${entry.liuHe}六合，与${entry.heHui.join("、")}三合，冲${entry.chong}，害${entry.hai}。`);
    if (score >= 80) parts.push("姓名与生肖高度匹配，大吉。");
    else if (score >= 60) parts.push("姓名与生肖较匹配，尚可。");
    else if (score >= 40) parts.push("姓名与生肖匹配度偏低，建议调整。");
    else parts.push("姓名与生肖严重相冲，不宜使用。");
    return parts.join("");
  })();

  return {
    shengXiao,
    score,
    xiYongMatches,
    jiYongMatches,
    heHui: entry.heHui.join("、"),
    liuHe: entry.liuHe,
    chong: entry.chong,
    hai: entry.hai,
    namingTips: entry.namingTips,
    analysis,
  };
}

/** 根据出生年份获取生肖 */
export function getShengXiaoByYear(year: number): ShengXiao {
  const shengXiaoList: ShengXiao[] = ["猴","鸡","狗","猪","鼠","牛","虎","兔","龙","蛇","马","羊"];
  return shengXiaoList[year % 12];
}

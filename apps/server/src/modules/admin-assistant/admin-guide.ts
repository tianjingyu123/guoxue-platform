/** 按当前页面路由给助手补充针对性上下文（页面感知：员工在哪，助手就更懂他要干嘛） */
export function pageHint(page: string): string {
  const p = (page || "").toLowerCase();
  if (p.includes("/courses/create") || (p.includes("/courses/") && p.includes("/edit"))) {
    return "员工正在课程新建/编辑页。重点：新建时只有'基本信息'标签是正常的，点'保存课程'后才会出现'章节管理'等标签；加章节要在保存后的'章节管理'里做，视频本地上传、可勾试看。";
  }
  if (p.includes("/courses")) return "员工在课程列表页。可指导新建课程、审核、上下架、筛选。";
  if (p.includes("/products") || p.includes("/shop")) {
    return "员工在商品/商城页。重点：编辑商品弹窗里有富文本详情、本地上传图片（带预览）、SKU 管理、上下架/删除。";
  }
  if (p.includes("/video")) return "员工在社区视频页。视频和封面都是本地上传。";
  if (p.includes("/circle")) return "员工在圈子管理页。";
  if (p.includes("/article") || p.includes("/content")) return "员工在内容/文章页，含富文本编辑与本地上传图片。";
  if (p.includes("/coin") || p.includes("/gift")) return "员工在虚拟币/礼物配置页，礼物图标为本地上传。";
  if (p.includes("/marketing")) return "员工在营销页（海报/落地页/优惠券等），海报图片为本地上传。";
  return "";
}

/** 格式化最近的变更日志（注入运营助手 system prompt） */
export function formatChangelog(maxItems = 15): string {
  const lines: string[] = [];
  let count = 0;
  for (const entry of ADMIN_CHANGELOG) {
    for (const item of entry.items) {
      if (count >= maxItems) break;
      lines.push(`- [${entry.date}] ${item}`);
      count++;
    }
    if (count >= maxItems) break;
  }
  if (!lines.length) return "";
  return `# 后台最近变更（最新在前·员工的问题很可能与这些变化有关）\n${lines.join("\n")}`;
}

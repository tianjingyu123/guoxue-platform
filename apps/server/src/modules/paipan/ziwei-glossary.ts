/** 词条索引：长词优先，避免「化禄」被「禄」之类的短词抢先命中 */
const TERM_INDEX: { key: string; term: GlossaryTerm }[] = ZIWEI_GLOSSARY.flatMap((t) => [
  { key: t.term, term: t },
  ...(t.alias ?? []).map((a) => ({ key: a, term: t })),
]).sort((a, b) => b.key.length - a.key.length);

/** 正文里出现了哪些术语，随报告附带（不下发整本词典） */
export function extractZiweiGlossary(texts: string[]): GlossaryTerm[] {
  const joined = texts.filter(Boolean).join("\n");
  if (!joined) return [];
  const hit = new Map<string, GlossaryTerm>();
  for (const { key, term } of TERM_INDEX) {
    if (hit.has(term.term)) continue;
    // 与八字词表同一条规矩：单字匹配会大面积误伤，正文只按两字以上的词匹配
    if (key.length < 2) continue;
    if (joined.includes(key)) hit.set(term.term, term);
  }
  return [...hit.values()].sort((a, b) => b.term.length - a.term.length);
}

export function findZiweiTerm(word: string): GlossaryTerm | undefined {
  const w = (word || "").trim();
  if (!w) return undefined;
  return TERM_INDEX.find((x) => x.key === w)?.term;
}
